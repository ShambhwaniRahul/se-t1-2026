import google.generativeai as genai
from google.colab import userdata
from PIL import Image
import json

# 2. Authenticate using the Colab Secret you just saved
API_KEY = userdata.get('GEMINI_API_KEY')
genai.configure(api_key=API_KEY)

# 3. Load the fast, free, multimodal model
model = genai.GenerativeModel('gemini-2.5-flash')

# 4. Load your invoice image (Change the filename if yours is different)
image_path = '/content/AN Enterprises.JPG'
try:
    invoice_image = Image.open(image_path)
except FileNotFoundError:
    print(f"Error: Please upload an image named '{image_path}' to Colab first.")
    exit()

# 5. The System Prompt (Hardened against hallucinations)
prompt = """
You are an expert data extraction AI.
Analyze the provided vendor invoice image and extract the overall invoice details as well as all purchased items.

CRITICAL RULES:
1. ONLY extract data that is physically visible in the image.
2. If a column, field, or value (like rate, price, or amount) is missing from the image, you MUST set its value strictly to null.
3. DO NOT guess, DO NOT hallucinate, and DO NOT mathematically calculate any missing prices or totals.

Return the data STRICTLY as a valid JSON object.
Do NOT wrap the output in markdown blocks (like ```json). Just return the raw JSON text.

Use this exact schema:
{
  "invoice_number": "Extract the invoice or bill number (string, or null if not found)",
  "date": "Extract the date in YYYY-MM-DD format (string, or null if not found)",
  "items": [
    {
      "sku": "Name of the ingredient or product",
      "quantity": <number or null>,
      "unit": "kg, L, pcs, boxes, etc. (infer from context if missing)",
      "price_per_unit": <number or null>,
      "total_price": <number or null>
    }
  ]
}
"""

# 6. Execute the Vision AI Request
print("Sending image to Gemini 2.5 Flash...\n")
response = model.generate_content([prompt, invoice_image])

# 7. Parse and display the result
try:
    # Convert the text response into an actual Python dictionary/list
    extracted_data = json.loads(response.text)

    print("✅ Extraction Successful! Here is the structured JSON:")
    print(json.dumps(extracted_data, indent=2))

except json.JSONDecodeError:
    print("❌ Failed to parse JSON. Here is the raw text Gemini returned:")
    print(response.text)
